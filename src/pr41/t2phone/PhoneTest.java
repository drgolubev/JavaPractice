package pr41.t2phone;

/*
 * Проверка задания 2: создаём три телефона разными конструкторами и вызываем все методы.
 */
public class PhoneTest {

    public static void main(String[] args) {
        // 1) Три экземпляра класса (заодно используем все три конструктора)
        Phone p1 = new Phone("+7 900 111-22-33", "iPhone 15", 171);   // 3 параметра
        Phone p2 = new Phone("+7 900 444-55-66", "Samsung S24");       // 2 параметра (вес = 0.0)
        Phone p3 = new Phone();                                        // без параметров

        Phone[] phones = {p1, p2, p3};

        for (Phone p : phones) {
            // 2) Значения переменных
            p.printInfo();
            // 6) Вызов методов для каждого объекта
            p.receiveCall("Денис");
            System.out.println("Номер: " + p.getNumber());
            System.out.println();
        }

        // 12) Перегруженный метод с двумя параметрами
        p1.receiveCall("Мама", "+7 900 777-88-99");

        // 13), 14) Метод с переменным числом аргументов: можно передать сколько угодно номеров
        p1.sendMessage("+7 900 000-00-01");
        p1.sendMessage("+7 900 000-00-01", "+7 900 000-00-02", "+7 900 000-00-03");
    }
}
