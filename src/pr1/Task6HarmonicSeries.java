package pr1;

/*
 * ПРАКТИЧЕСКАЯ РАБОТА №1, задание 6.
 * Вывести первые 10 чисел гармонического ряда: 1, 1/2, 1/3, ..., 1/10.
 * "Форматировать вывод" — используем printf, чтобы числа были в ровных столбиках
 * и с одинаковым количеством знаков после запятой.
 */
public class Task6HarmonicSeries {

    public static void main(String[] args) {
        double partialSum = 0; // заодно покажем частичную сумму ряда

        System.out.println(" n |  1/n    | сумма до n");
        System.out.println("---+---------+-----------");

        for (int n = 1; n <= 10; n++) {
            double term = 1.0 / n; // 1.0 (а не 1), чтобы деление было дробным, а не целочисленным
            partialSum += term;
            // %2d  — целое число шириной 2 символа
            // %.5f — дробное число с 5 знаками после запятой
            // %n   — перевод строки
            System.out.printf("%2d | %.5f | %.5f%n", n, term, partialSum);
        }
    }
}
