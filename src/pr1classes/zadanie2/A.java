package pr1classes.zadanie2;

/*
 * ПР1 «Классы. Создание объектов», Задание 2 (самостоятельно):
 * Что будет отображено в консоли следующей программой?
 *
 * ОТВЕТ:  false
 *
 * ПОЧЕМУ:
 *   x — это ПОЛЕ класса (переменная экземпляра), а не локальная переменная метода.
 *   Полям Java автоматически присваивает значения по умолчанию:
 *       boolean → false,  числа → 0,  char → '\u0000',  ссылочные типы (String и т.п.) → null.
 *   Мы нигде не присвоили x значение, поэтому a.x == false.
 *   (Для сравнения: если бы x был локальной переменной внутри main и мы бы её не
 *   инициализировали, была бы ошибка компиляции — локальным переменным значения
 *   по умолчанию не даются.)
 */
public class A {
    boolean x;

    public static void main(String[] args) {
        A a = new A();
        System.out.println(a.x); // выведет: false
    }
}
