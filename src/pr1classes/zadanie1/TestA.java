/*
 * Клиент класса A (исправленная версия). Объяснение ошибки — в комментарии в файле A.java.
 */
public class TestA {
    public static void main(String[] args) {
        // Теперь это компилируется, потому что в A добавлен конструктор A()
        A a = new A();
        a.print();

        // Второй способ исправления — вызвать существующий конструктор с параметром
        A b = new A("Объект создан конструктором A(String)");
        b.print();
    }
}
