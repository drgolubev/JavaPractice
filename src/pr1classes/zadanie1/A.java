package pr1classes.zadanie1;

/*
 * ПР1 «Классы. Создание объектов», Задание 1 (самостоятельно): найти и исправить ошибки.
 *
 * ИСХОДНЫЙ КОД С ОШИБКОЙ:
 *     public class A {
 *         String s;
 *         A(String newS) { s = newS; }
 *         public void print() { System.out.print(s); }
 *     }
 *     class TestA {
 *         public static void main(String[] args) {
 *             A a = new A();      // <-- ОШИБКА КОМПИЛЯЦИИ
 *             a.print();
 *         }
 *     }
 *
 * В ЧЁМ ОШИБКА:
 *   В строке  new A()  вызывается конструктор БЕЗ аргументов, но в классе A его нет.
 *   В классе объявлен только конструктор A(String newS).
 *   Конструктор по умолчанию (пустой, без аргументов) Java создаёт автоматически
 *   ТОЛЬКО если в классе не написано ни одного конструктора. Здесь конструктор написан,
 *   поэтому конструктора по умолчанию нет → ошибка компиляции
 *   "constructor A in class A cannot be applied to given types".
 *
 * КАК ИСПРАВИТЬ (любой из двух способов):
 *   1) Добавить в класс A конструктор без аргументов (сделано ниже).
 *   2) Или в TestA вызывать существующий конструктор: new A("какой-то текст").
 */
public class A {
    String s;

    /** Исправление: явно добавленный конструктор без аргументов. */
    A() {
        s = "Объект создан конструктором без аргументов";
    }

    /** Исходный конструктор с параметром. */
    A(String newS) {
        s = newS;
    }

    public void print() {
        System.out.println(s);
    }
}
