package pr1classes.rectangle;

/*
 * ПР1 «Классы», Задание №1: класс Rectangle (прямоугольник), сделан по примеру класса Circle.
 *
 * UML-диаграмма класса (её нужно перерисовать на бумаге / в draw.io):
 *
 *   +--------------------------------------+
 *   |              Rectangle               |
 *   +--------------------------------------+
 *   | width: double = -1                   |
 *   | height: double = -1                  |
 *   +--------------------------------------+
 *   | Rectangle()                          |
 *   | Rectangle(newWidth: double,          |
 *   |           newHeight: double)         |
 *   | getArea(): double                    |
 *   | getPerimeter(): double               |
 *   +--------------------------------------+
 *
 *   Верхний отсек — имя класса, средний — поля данных (имя: тип),
 *   нижний — конструкторы и методы (имяМетода(параметр: тип): типВозвращаемогоЗначения).
 */
public class Rectangle {

    /** Ширина прямоугольника. Значение по умолчанию -1 (как требует задание). */
    double width = -1;

    /** Высота прямоугольника. Значение по умолчанию -1. */
    double height = -1;

    /**
     * Безаргументный конструктор — создаёт прямоугольник со значениями по умолчанию (-1 и -1).
     * Тело пустое, потому что поля уже инициализированы при объявлении.
     */
    Rectangle() {
    }

    /** Конструктор, создающий прямоугольник с указанными шириной и высотой. */
    Rectangle(double newWidth, double newHeight) {
        width = newWidth;
        height = newHeight;
    }

    /** Возвращает площадь: ширина * высота. */
    double getArea() {
        return width * height;
    }

    /** Возвращает периметр: 2 * (ширина + высота). */
    double getPerimeter() {
        return 2 * (width + height);
    }
}
